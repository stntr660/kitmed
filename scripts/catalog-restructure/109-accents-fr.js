// ---------------------------------------------------------------- plan
// rows: active product translations { id, product_id, constructeur, language_code, nom, description, fiche_technique }
function planRows(rows) {
  const changes = [];
  for (const t of rows) {
    const fixed = {};
    if (t.language_code === "fr") for (const f of FIELDS_FR) fixed[f] = fixText(t[f]);
    const over = (FIELDS[t.product_id] || {})[t.language_code] || {};
    Object.assign(fixed, over);
    for (const [field, to] of Object.entries(fixed)) {
      if (to === t[field] || to == null) continue;
      changes.push({ table: "product_translations", rowId: t.id, field, brand: t.constructeur, label: `${t.product_id} ${t.language_code}.${field}`, from: t[field], to });
    }
  }
  return changes;
}

// word-level diff for the review file
function wordDiff(a, b) {
  const A = (a || "").split(/(\s+)/), B = (b || "").split(/(\s+)/);
  if (A.length !== B.length) return `   - ${a}\n   + ${b}`;
  const out = [];
  for (let i = 0; i < A.length; i++) if (A[i] !== B[i]) out.push(`${A[i]} -> ${B[i]}`);
  return "   " + out.join(" | ");
}

function report(changes) {
  const byBrand = {};
  const prods = {};
  for (const c of changes) {
    const pid = c.label.split(" ")[0];
    (prods[c.brand] = prods[c.brand] || new Set()).add(pid);
  }
  for (const [b, s] of Object.entries(prods)) byBrand[b] = s.size;
  const lines = [];
  for (const c of changes) lines.push(`## ${c.brand} ${c.label}\n${wordDiff(c.from, c.to)}\n   AFTER: ${(c.to || "").replace(/\n/g, " / ")}`);
  fs.writeFileSync(DIFF_FILE, lines.join("\n") + "\n");
  const nP = Object.values(byBrand).reduce((s, n) => s + n, 0);
  console.log(`products by brand: ${JSON.stringify(byBrand)}`);
  console.log(`${changes.length} field(s) on ${nP} product(s) to change; diff -> ${DIFF_FILE}`);
}

async function loadRows(prisma) {
  const prods = await prisma.products.findMany({ where: { status: "active" }, select: { id: true, constructeur: true } });
  const brand = Object.fromEntries(prods.map((p) => [p.id, p.constructeur]));
  const trs = await prisma.product_translations.findMany({ where: { product_id: { in: prods.map((p) => p.id) } } });
  return trs.map((t) => ({ ...t, constructeur: brand[t.product_id] }));
}

async function main() {
  if (INPUT) { report(planRows(JSON.parse(fs.readFileSync(INPUT, "utf8")))); return; }
  const { PrismaClient } = require("@prisma/client");
  const prisma = new PrismaClient();
  try {
    if (REVERT) {
      if (!fs.existsSync(BEFORE_FILE)) throw new Error(`${BEFORE_FILE} missing`);
      const before = JSON.parse(fs.readFileSync(BEFORE_FILE, "utf8"));
      for (const f of before.fields) await prisma[f.table].update({ where: { id: f.rowId }, data: { [f.field]: f.value } });
      console.log(`reverted ${before.fields.length} field(s) from ${BEFORE_FILE}\n=== REVERTED ===`);
      return;
    }
    const changes = planRows(await loadRows(prisma));
    report(changes);
    if (!APPLY) { console.log("[DRY-RUN] Re-run with --apply (or --revert)"); return; }
    if (!changes.length) { console.log("nothing to do\n=== DONE ==="); return; }
    const before = fs.existsSync(BEFORE_FILE) ? JSON.parse(fs.readFileSync(BEFORE_FILE, "utf8")) : { taken_at: new Date().toISOString(), fields: [] };
    for (const c of changes) {
      if (!before.fields.find((f) => f.table === c.table && f.rowId === c.rowId && f.field === c.field)) {
        before.fields.push({ table: c.table, rowId: c.rowId, field: c.field, label: c.label, value: c.from });
      }
    }
    fs.writeFileSync(BEFORE_FILE, JSON.stringify(before, null, 1)); // snapshot first, then write
    for (const c of changes) await prisma[c.table].update({ where: { id: c.rowId }, data: { [c.field]: c.to } });
    console.log(`applied ${changes.length} change(s); snapshot ${BEFORE_FILE} (${before.fields.length} field(s))\n=== DONE ===`);
  } finally {
    await prisma.$disconnect();
  }
}

main().catch((e) => { console.error(e); process.exit(1); });
