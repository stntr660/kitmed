// ---------------------------------------------------------------- 2) word pass
const TOKEN = /[\p{L}]+/gu;
// capitalised words kept as is: lens names (Landers Equatorial, High Definition) and
// the English « MDR (Medical Device Regulation) »
const CAP_SKIP = new Set(["Equatorial", "Definition", "Medical", "Regulation"]);
const cap = (s) => s.charAt(0).toUpperCase() + s.slice(1);
function fixText(text) {
  if (!text) return text;
  let t = text;
  for (const [re, to] of RULES) t = t.replace(re, to);
  t = t.replace(TOKEN, (w) => {
    if (w.length > 1 && w === w.toUpperCase()) return w; // brands, codes
    if (CAP_SKIP.has(w)) return w; // product / English names
    const lw = w.toLowerCase();
    const to = DICT[lw];
    if (!to) return w;
    if (w === lw) return to;
    if (w === cap(lw)) return cap(to);
    return w; // mixed case (AirTex...) -> untouched
  });
  return t;
}

